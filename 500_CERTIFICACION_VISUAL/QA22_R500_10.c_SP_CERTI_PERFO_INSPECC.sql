--		 EXECUTE [dbo].[PG_LI_ALERTA_INICIAL_X_TIPO] 0,139,1
--		 EXECUTE [dbo].[PG_LI_ALERTA_INICIAL_X_TIPO] 0,139,2
--		 EXECUTE [dbo].[PG_LI_ALERTA_INICIAL_X_TIPO] 0,139,3
CREATE PROCEDURE [dbo].[PG_LI_ALERTA_INICIAL_X_TIPO]
	@PP_K_SISTEMA_EXE				INT,
	@PP_K_USUARIO_ACCION			INT,
	-- ===========================
	@PP_K_TIPO_PROCESO				INT
AS
DECLARE		 @VP_MENSAJE				NVARCHAR(MAX)	= ''
			,@VP_ENCABEZADO_MENSAJE		NVARCHAR(MAX)	= ''
			,@VP_L_MOSTRAR_NOTIFICACION	INT				= 1
BEGIN TRANSACTION 
BEGIN TRY													  	
	DECLARE	@VP_TA_ALERTAS	AS TABLE
	(		TA_K_ALERTA				INTEGER IDENTITY(1,1),
			TA_O_ALERTA				INT,
			TA_L_IMAGEN_FINAL		INT,
			TA_RUTA					NVARCHAR(MAX),
			TA_MENSAJE				NVARCHAR(MAX),
			TA_ENCABEZADO_MENSAJE	NVARCHAR(MAX)		)

	DECLARE  @VP_CU_RUTA			NVARCHAR(MAX)	= ''
			,@VP_CONTADOR			INTEGER			= 0

	DECLARE CU_CURSOR				CURSOR LOCAL STATIC FOR
		SELECT	CONCAT(ALERTA_CALIDAD_RUTA_CARPETA	,	ALERTA_CALIDAD_IMAGEN )-- AS RUTA,'' ,--AS ENCABEZADO_MENSAJE,= '' --AS MENSAJE
		FROM	PPMS_PEARL.dbo.ALERTA_CALIDAD_INICIAL	(NOLOCK)
		INNER JOIN	PPMS_PEARL.DBO.ALERTA_CALIDAD_IMAGEN	ON ALERTA_CALIDAD_IMAGEN.K_ALERTA_CALIDAD_IMAGEN	= ALERTA_CALIDAD_INICIAL.K_ALERTA_CALIDAD_IMAGEN
		WHERE	K_TIPO_PROCESO				= @PP_K_TIPO_PROCESO
		AND		L_ALERTA_CALIDAD_INICIAL	= 1
		AND		L_ALERTA_CALIDAD_IMAGEN		= 1
		ORDER	BY K_ALERTA_CALIDAD_INICIAL ASC
	OPEN CU_CURSOR
		FETCH NEXT FROM CU_CURSOR INTO	@VP_CU_RUTA			
		WHILE @@FETCH_STATUS = 0
		BEGIN
			SET @VP_CONTADOR+=1
			
			INSERT INTO	@VP_TA_ALERTAS
			VALUES	( @VP_CONTADOR, 0, @VP_CU_RUTA, '', '')

		FETCH NEXT FROM CU_CURSOR INTO	@VP_CU_RUTA
		END
	CLOSE CU_CURSOR
	DEALLOCATE CU_CURSOR
		
		DECLARE @VP_CANTIDAD_REGISTROS AS INTEGER
		SELECT	@VP_CANTIDAD_REGISTROS	= COUNT(TA_K_ALERTA) 
		FROM	@VP_TA_ALERTAS

		IF ( @VP_CANTIDAD_REGISTROS	) <= 0
		BEGIN
			SET	@VP_L_MOSTRAR_NOTIFICACION	= 0
			SET @VP_MENSAJE = 'Proceso sin registros (BD) '	--	+ CHAR(13) + CHAR(10)
			RAISERROR (@VP_MENSAJE, 16, 1 )
		END
		ELSE
		BEGIN
			UPDATE	@VP_TA_ALERTAS
			SET		TA_L_IMAGEN_FINAL	= 1
			WHERE	TA_K_ALERTA		IN (	SELECT	TOP(1)	TA_K_ALERTA
											FROM	@VP_TA_ALERTAS
											ORDER	BY TA_K_ALERTA DESC	)
		END

			--SET @VP_MENSAJE = 'ERROR MANUAL PARA PRUEBAS '	--	+ CHAR(13) + CHAR(10)
			--RAISERROR (@VP_MENSAJE, 16, 1 )

COMMIT TRANSACTION 
END TRY
BEGIN CATCH
	--	OCURRIÓ UN ERROR, DESHACEMOS LOS CAMBIOS
	ROLLBACK TRANSACTION
	DECLARE @ErrorMessage NVARCHAR(4000);
	SET @ErrorMessage = ERROR_MESSAGE() 
	SET @VP_MENSAJE = 'ERROR: // ' + @ErrorMessage
	
	SET	@VP_ENCABEZADO_MENSAJE		= 'SIN ALERTAS'
END CATCH	

IF	@VP_MENSAJE <> ''
BEGIN
	SELECT	@VP_MENSAJE AS MENSAJE, @VP_ENCABEZADO_MENSAJE AS ENCABEZADO_MENSAJE	--, @VP_L_MOSTRAR_NOTIFICACION AS L_MOSTRAR_NOTIFICACION
END
ELSE
BEGIN
	SELECT	TA_L_IMAGEN_FINAL		AS L_IMAGEN_FINAL	,
			TA_RUTA					AS RUTA_IMAGEN		,
			@VP_CANTIDAD_REGISTROS	AS TOTAL_REGISTROS	,
			TA_MENSAJE				AS MENSAJE			,
			TA_ENCABEZADO_MENSAJE	AS ENCABEZADO_MENSAJE
	FROM	@VP_TA_ALERTAS
	ORDER	BY TA_O_ALERTA ASC
END
 --	//////////////////////////////////////////////////////////////
GO


