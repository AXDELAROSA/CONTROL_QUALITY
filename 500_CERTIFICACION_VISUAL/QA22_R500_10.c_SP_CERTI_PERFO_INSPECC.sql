AS
DECLARE		 @VP_ENCABEZADO_MENSAJE			NVARCHAR(MAX)	= ''
			,@VP_MENSAJE					NVARCHAR(MAX)	= ''
			-- ==================================================
BEGIN TRANSACTION 
BEGIN TRY
	DELETE
	FROM	PERFORACION
	WHERE	ESTACION		=	@PP_ESTACION	-- '" & ESTACION & "' 
	AND		NOSERIE			<>	@PP_SERIAL		-- '" & SERIAL & "' 
	AND		[STATUS]		=	'PROCESO'
	IF @@ROWCOUNT = 0
	BEGIN
		SET @VP_MENSAJE =	'No fue posible quitar la caja del proceso.' + CHAR(13)	+	CHAR(10) + ' Informe a Sistemas!!!(BD)...'	
		RAISERROR (@VP_MENSAJE, 16, 1 ) 
	END

COMMIT TRANSACTION 
END TRY
BEGIN CATCH
	--	OCURRIÓ UN ERROR, DESHACEMOS LOS CAMBIOS
	ROLLBACK TRANSACTION
	DECLARE @ErrorMessage NVARCHAR(4000);
	SET @ErrorMessage = ERROR_MESSAGE() 
	SET @VP_MENSAJE = 'ERROR: // ' + @ErrorMessage

	SET	@VP_ENCABEZADO_MENSAJE = 'Error de proceso'
END CATCH	
		-- ===================================================
