			SELECT	COMP_ITEM_NO
			FROM	DATA_02.DBO.IMKITFIL_SQL	(NOLOCK)
			WHERE	ITEM_NO						= @VP_U_ITEM
		END
		ELSE
		BEGIN		
			INSERT INTO @VP_TA_ITEMS
			SELECT	@PP_VALOR_ITEMNO
		END
	END

