		FETCH NEXT FROM CU_CURSOR INTO	@VP_CU_ITEM_NO		,	@VP_CU_MODELNO		,	@VP_CU_VERSIONNO		,
										@VP_CU_COMP_ITEM_NO	,	@VP_CU_CUS_ITEM_NO	,	@VP_CU_USER_DEF_FLD_4	,
