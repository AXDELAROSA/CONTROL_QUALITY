			@VP_CU_USER_DEF_FLD_4	VARCHAR(250),
			@VP_CU_REFERENCE_1		VARCHAR(250)

	DECLARE CU_CURSOR				CURSOR LOCAL STATIC FOR
		SELECT	CCPRDSTR_SQL.ITEM_NO		,	LTRIM(RTRIM(CCPRDSTR_SQL.MODELNO))		,	--		AS MODELO,
