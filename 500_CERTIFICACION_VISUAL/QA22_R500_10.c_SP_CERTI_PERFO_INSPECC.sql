	DROP PROCEDURE [dbo].[PG_LI_AYUDAS_VISUALES_CERTIFICACION]
GO
--		 EXECUTE [dbo].[PG_LI_AYUDAS_VISUALES_CERTIFICACION] 0,139
CREATE PROCEDURE [dbo].[PG_LI_AYUDAS_VISUALES_CERTIFICACION]
	@PP_K_SISTEMA_EXE				INT,
	@PP_K_USUARIO_ACCION			INT
	-- ===========================
AS
DECLARE		 @VP_MENSAJE		NVARCHAR(MAX)	= ''
			,@VP_SERVIDOR		NVARCHAR(MAX)	= ''
			,@VP_RUTA			NVARCHAR(MAX)	= ''
BEGIN TRANSACTION 
BEGIN TRY													  
	
	SELECT	TOP(1)
			@VP_SERVIDOR	= ISNULL(SERVIDOR,''),
			@VP_RUTA		= ISNULL(RUTA,'')
	FROM	BD_GENERAL.dbo.RUTA_ARCHIVO	(NOLOCK)
	WHERE	LTRIM(RTRIM(D_RUTA_ARCHIVO)) = 'AYUDAS_VISUALES_CERTIFICACION'
	IF @@ROWCOUNT = 0
	BEGIN
		SET @VP_MENSAJE = '[NO] se encontró la ruta (BD) '+ CHAR(13) + CHAR(10) + ' Vuelve a intentar, si el error persiste informe a [SISTEMAS]....'
		RAISERROR (@VP_MENSAJE, 16, 1 ) 
	END

COMMIT TRANSACTION 
END TRY
BEGIN CATCH
	--	OCURRIÓ UN ERROR, DESHACEMOS LOS CAMBIOS
	ROLLBACK TRANSACTION
	DECLARE @ErrorMessage NVARCHAR(4000);
	SET @ErrorMessage = ERROR_MESSAGE() 
	SET @VP_MENSAJE = 'ERROR: // ' + @ErrorMessage
END CATCH	

SELECT	@VP_MENSAJE AS MENSAJE, @VP_SERVIDOR AS SERVIDOR, @VP_RUTA AS RUTA
 --	//////////////////////////////////////////////////////////////
GO


