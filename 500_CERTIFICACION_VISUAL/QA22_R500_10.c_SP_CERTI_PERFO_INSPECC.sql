--		 EXECUTE [dbo].[PG_DL_PROCESO_PERFORACION] 0,139,1, 49903008,'IT-010'
CREATE PROCEDURE [dbo].[PG_DL_PROCESO_PERFORACION]
	@PP_K_SISTEMA_EXE				INT,
	@PP_K_USUARIO_ACCION			INT,
	-- ===========================
	@PP_TIPO_PROCESO				NVARCHAR(MAX),
	@PP_SERIAL						NVARCHAR(MAX),
