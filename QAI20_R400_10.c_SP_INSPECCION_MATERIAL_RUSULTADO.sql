/*
 EXEC	[dbo].[PG_LI_AUTORIZAR_MATERIAL_ORDEN] 0,0, 10,'10-001',35
*/

CREATE PROCEDURE [dbo].[PG_LI_AUTORIZAR_MATERIAL_ORDEN]
	@PP_K_SISTEMA_EXE				INT,
	@PP_K_USUARIO_ACCION			INT,
	-- ===========================
	@PP_K_ORDEN_COMPRA				INT,
	@PP_ORDEN_COMPRA_PEDIDO			VARCHAR(50),
	@PP_K_ITEM						INT
	
AS

	DECLARE @VP_MENSAJE						VARCHAR(300) = ''
	-- ///////////////////////////////////////////

	SELECT	
			[INSPECCION_MATERIAL_ORDEN].*,
			INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL,
			INSPECCION_MATERIAL.INSPECCION,
			INSPECCION_MATERIAL.INSPECCION_PORCENTAJE,
			PART_NUMBER_ITEM_PEARL AS NUMERO_PARTE,
			-- =============================	
			( CASE WHEN K_TIPO_INSPECCION_MATERIAL = 2
						THEN OPCION_1
				ELSE 'N/A'	END )	AS VALOR_MINIMO,
			-- =============================	
			( CASE WHEN K_TIPO_INSPECCION_MATERIAL = 2
						THEN OPCION_2
				ELSE 'N/A'	END )	AS VALOR_MAXIMO,
			BD_GENERAL.dbo.USUARIO_PEARL.D_USUARIO_PEARL
			-- =============================	
	FROM	[INSPECCION_MATERIAL_ORDEN]
	 INNER JOIN COMPRAS_PRUEBAS.dbo.ITEM ON [INSPECCION_MATERIAL_ORDEN].K_ITEM = ITEM.K_ITEM
	INNER JOIN INSPECCION_MATERIAL ON [INSPECCION_MATERIAL_ORDEN].K_INSPECCION_MATERIAL = INSPECCION_MATERIAL.K_INSPECCION_MATERIAL
			AND [INSPECCION_MATERIAL_ORDEN].K_ITEM = INSPECCION_MATERIAL.K_ITEM
	INNER JOIN	INSPECCION_OPCION ON INSPECCION_MATERIAL.K_INSPECCION_MATERIAL = INSPECCION_OPCION.K_INSPECCION_MATERIAL
	INNER JOIN	BD_GENERAL.dbo.USUARIO_PEARL ON	[INSPECCION_MATERIAL_ORDEN].K_USUARIO_CAMBIO = BD_GENERAL.dbo.USUARIO_PEARL.K_USUARIO_PEARL
	-- =============================
	WHERE	K_ORDEN_COMPRA = @PP_K_ORDEN_COMPRA
	AND		ORDEN_COMPRA_PEDIDO = @PP_ORDEN_COMPRA_PEDIDO
	AND		[INSPECCION_MATERIAL_ORDEN].K_ITEM = @PP_K_ITEM
	-- ////////////////////////////////////////////////
	-- ////////////////////////////////////////////////
GO




