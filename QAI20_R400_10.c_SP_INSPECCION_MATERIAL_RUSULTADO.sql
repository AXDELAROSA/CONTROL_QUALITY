CREATE PROCEDURE [dbo].[PG_SK_INSPECCION_MATERIAL_ORDEN_RESULTADO]
	@PP_K_SISTEMA_EXE				INT,
	@PP_K_USUARIO_ACCION			INT,
	-- ===========================
	@PP_K_ORDEN_COMPRA				INT,
	@PP_ORDEN_COMPRA_PEDIDO			VARCHAR(50),
	@PP_K_ITEM						INT
AS

	DECLARE @VP_MENSAJE						VARCHAR(300) = ''
	-- ///////////////////////////////////////////

	SELECT	
			[INSPECCION_MATERIAL_ORDEN_RESULTADO].*,
			-- ===========================
		( CASE WHEN ISNULL(INSPECCION_TERMINADA, 0) = 1 AND ISNULL(APROBACION_SISTEMA, 0) = 1
				THEN 'ACEPTADO SISTEMA'
			WHEN ISNULL(INSPECCION_TERMINADA, 0) = 1 AND ISNULL(APROBACION_SISTEMA, 0) = 0 AND ISNULL(APROBACION_MANUAL, 0) = 1
				THEN 'ACEPTADO MANUAL'
			WHEN ISNULL(INSPECCION_TERMINADA, 0) = 1 AND ISNULL(APROBACION_SISTEMA, 0) = 0 AND ISNULL(APROBACION_MANUAL, 0) = 0
				THEN 'RECHAZADO'
			WHEN ISNULL(INSPECCION_TERMINADA, 0) = 0 
				THEN 'PENDIENTE' END ) AS ESTATUS,
		-- ===========================
		PART_NUMBER_ITEM_PEARL
	-- =============================	
	FROM	[INSPECCION_MATERIAL_ORDEN_RESULTADO]
	INNER JOIN	COMPRAS_PRUEBAS.dbo.ITEM		ON	[INSPECCION_MATERIAL_ORDEN_RESULTADO].K_ITEM=ITEM.K_ITEM
	-- =============================
	WHERE	K_ORDEN_COMPRA = @PP_K_ORDEN_COMPRA
	AND		ORDEN_COMPRA_PEDIDO = @PP_ORDEN_COMPRA_PEDIDO
	AND		[INSPECCION_MATERIAL_ORDEN_RESULTADO].K_ITEM = @PP_K_ITEM
	-- ////////////////////////////////////////////////
	-- ////////////////////////////////////////////////
GO




