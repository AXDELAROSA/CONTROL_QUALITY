CREATE PROCEDURE [dbo].[PG_UP_INSPECCION_MATERIAL_ORDEN_RESULTADO_APROBACION]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO_ACCION		INT,
	-- ===========================
	@PP_K_ORDEN_COMPRA			INT,
	@PP_ORDEN_COMPRA_PEDIDO		VARCHAR(50),
	@PP_K_ITEM					INT,
	@PP_APROBACION				INT,
	@PP_D_USUARIO_AUTORIZACION	VARCHAR(150),
	@PP_COMENTARIO				VARCHAR(255)
AS

	DECLARE @VP_MENSAJE		VARCHAR(300) = ''

	-- // SECCION#1 /////////////////////////////////////////////////////////// VALIDACIONES + REGLAS DE NEGOCIO 
	
	IF @VP_MENSAJE=''
		--EXECUTE [dbo].[PG_RN_INSPECCION_MATERIAL_DELETE]	@PP_K_SISTEMA_EXE, @PP_K_USUARIO_ACCION,
		--									@PP_K_INSPECCION_MATERIAL, 
		--									@OU_RESULTADO_VALIDACION = @VP_MENSAJE		OUTPUT

	-- // SECCION#2 ////////////////////////////////////////////////////////// ACCION A REALIZAR

	IF @VP_MENSAJE=''
		BEGIN
			BEGIN TRANSACTION 
			BEGIN TRY
				DECLARE @VP_TIPO_INSPECCION_MATERIAL_LOG	INT = 1 -- APROBAR INSPECCION
				DECLARE @VP_APROBACION_SISTEMA_ANTERIOR		INT = 0
				DECLARE @VP_APROBACION_SISTEMA_NUEVO		INT = 0
				DECLARE @VP_APROBACION_MANUAL_ANTERIOR		INT = 0
				DECLARE @VP_APROBACION_MANUAL_NUEVO			INT = 0
				-- ===========================
				IF @PP_APROBACION = 0
					SET @VP_TIPO_INSPECCION_MATERIAL_LOG = 2 -- RECHAZAR INSPECCION
				-- ===========================

					SELECT	@VP_APROBACION_SISTEMA_ANTERIOR = APROBACION_SISTEMA,
							@VP_APROBACION_SISTEMA_NUEVO    = APROBACION_SISTEMA,
							@VP_APROBACION_MANUAL_ANTERIOR	= APROBACION_MANUAL,
							@VP_APROBACION_MANUAL_NUEVO		= APROBACION_MANUAL
															FROM	[INSPECCION_MATERIAL_ORDEN_RESULTADO]
															WHERE	K_ORDEN_COMPRA = @PP_K_ORDEN_COMPRA
															AND		ORDEN_COMPRA_PEDIDO = @PP_ORDEN_COMPRA_PEDIDO
															AND		K_ITEM = @PP_K_ITEM
															
				IF @PP_APROBACION = 0 AND @VP_APROBACION_SISTEMA_ANTERIOR = 1
					SET @VP_APROBACION_SISTEMA_NUEVO = 0
				-- ===========================

				-- ///////////////////SE VALIDA QUE EL ESTATUS ANTERIOR NO SEA IGUAL AL NUEVO////////////// 
				IF @PP_APROBACION = 0 AND @VP_APROBACION_SISTEMA_ANTERIOR = 0 AND @VP_APROBACION_MANUAL_ANTERIOR = 0
					RAISERROR ('ERROR: El material ya se encuentra Rechazado en [INSPECCION_MATERIAL_ORDEN_RESULTADO] ', 16, 1 ) --MENSAJE - Severity -State. 

				IF ( @PP_APROBACION = 1 AND @VP_APROBACION_SISTEMA_ANTERIOR = 1 OR @VP_APROBACION_MANUAL_ANTERIOR = 1 )
					RAISERROR ('ERROR: El material ya se encuentra Aceptado en [INSPECCION_MATERIAL_ORDEN_RESULTADO] ', 16, 1 ) --MENSAJE - Severity -State. 

				SET @VP_APROBACION_MANUAL_NUEVO = @PP_APROBACION
				
				-- ///////////////////SE OBTIENE EL USUARIO QUE AUTORIZO EL CAMBIO////////////// 
				DECLARE @VP_K_USUARIO_AUTORIZACION INT = 0
				SELECT  @VP_K_USUARIO_AUTORIZACION = K_USUARIO
				FROM	BD_GENERAL.DBO.[GRUPO_APROBADOR] 
				INNER	JOIN [BD_GENERAL].dbo.USUARIO_PEARL ON [GRUPO_APROBADOR].K_USUARIO = USUARIO_PEARL.K_USUARIO_PEARL
				WHERE	D_USUARIO_PEARL = @PP_D_USUARIO_AUTORIZACION	
				AND		D_GRUPO_APROBADOR = 'QA MADIFICAR INSPECCION MATERIAL'
				AND		K_ESTATUS_GRUPO_APROBADOR = 1 -- ACTIVO
				AND		K_TIPO_GRUPO_APROBADOR = 150 --  MODIFICAR INSPECCION MATERIAL QA

				IF @VP_K_USUARIO_AUTORIZACION IS NULL
					RAISERROR ('ERROR: No fue posible obtener usuario aprobador en [GRUPO_APROBADOR] ', 16, 1 ) --MENSAJE - Severity -State. 

				-- ///////////////////INGRESO EL LOG DEL CAMBIO REALIZADO EN LA INSPECCION DEL MATERIAL////////////// 
				EXECUTE [dbo].[PG_IN_INSPECCION_MATERIAL_LOG]	@PP_K_SISTEMA_EXE, @PP_K_USUARIO_ACCION,
																@VP_TIPO_INSPECCION_MATERIAL_LOG, @PP_K_ORDEN_COMPRA,
																@PP_ORDEN_COMPRA_PEDIDO, @PP_K_ITEM, 0, '', '',
																@VP_APROBACION_SISTEMA_ANTERIOR, @VP_APROBACION_SISTEMA_NUEVO, 
																@VP_APROBACION_MANUAL_ANTERIOR, @VP_APROBACION_MANUAL_NUEVO, 
																@VP_K_USUARIO_AUTORIZACION, @PP_COMENTARIO

				-- ///////////////////SE ACTUALIZA EL DATO//////////////////////////////////////////////////
				UPDATE [INSPECCION_MATERIAL_ORDEN_RESULTADO]
					SET [APROBACION_SISTEMA]						= ( CASE WHEN @PP_APROBACION = 0 AND @VP_APROBACION_SISTEMA_ANTERIOR = 1THEN @PP_APROBACION
																			ELSE [APROBACION_SISTEMA] END ),
						[APROBACION_MANUAL]							= @PP_APROBACION,
						[COMENTARIO]								= @PP_COMENTARIO,
						[K_USUARIO_ALTA]							= @PP_K_USUARIO_ACCION,
						[F_INSPECCION_MATERIAL_ORDEN_RESULTADO]		= GETDATE()	
				WHERE K_ITEM = @PP_K_ITEM
				AND K_ORDEN_COMPRA = @PP_K_ORDEN_COMPRA
				AND ORDEN_COMPRA_PEDIDO = @PP_ORDEN_COMPRA_PEDIDO

				IF @@ROWCOUNT = 0
					RAISERROR ('ERROR: No se Actualizo el estatus de la inspección', 16, 1 ) --MENSAJE - Severity -State.
				
				-- ///////////SI LA INSPECCION HA TERMINADO SE INGRESA EL REGISTRO PARA LA DISPOSICION///////////////////////////////////////////////////
				IF ( @VP_APROBACION_SISTEMA_ANTERIOR <> @VP_APROBACION_SISTEMA_NUEVO OR @VP_APROBACION_MANUAL_ANTERIOR <> @VP_APROBACION_MANUAL_NUEVO )
					BEGIN
						-- //////////////////////SE OBTIENE LA LOCACION MHI POR DEFAULT///////////////////////
						DECLARE @VP_LOCACION_DESTINO VARCHAR(5) = ''
							SELECT	@VP_LOCACION_DESTINO = LTRIM(RTRIM(LOC))
								FROM	imlocfil_sql 
							WHERE A4GLIdentity = 4
													
						-- //////////////////////SE OBTIENE LA LOCACION MQU SI EL RESULTADO DE LA INSPECCION ES RECHAZADO///////////////////////
						IF @VP_APROBACION_SISTEMA_NUEVO = 0 AND @VP_APROBACION_MANUAL_NUEVO = 0
							SELECT	@VP_LOCACION_DESTINO = LTRIM(RTRIM(LOC))
							FROM	imlocfil_sql 
							WHERE A4GLIdentity = 6
							
						IF @VP_LOCACION_DESTINO IS NULL
							RAISERROR ('ERROR: No fue posible obtener la locacion en [imlocfil_sql] ', 16, 1 ) --MENSAJE - Severity -State.
							
						IF @VP_LOCACION_DESTINO NOT IN ('MHI','MQU')
							RAISERROR ('ERROR: Locacion no valida.', 16, 1 ) --MENSAJE - Severity -State.

						-- //////////////////////SE VALIDA QUE EXISTA EL MATERIAL EN LA TABLA DE DISPOCISION///////////////////////
						DECLARE @VP_N_MATERIAL_ESPERA_DISPOSICION INT = 0
						SELECT @VP_N_MATERIAL_ESPERA_DISPOSICION =  K_INSPECCION_MATERIAL_ORDEN_ESPERA_DISPOSICION
						FROM [INSPECCION_MATERIAL_ORDEN_ESPERA_DISPOSICION]
						WHERE K_ORDEN_COMPRA = @PP_K_ORDEN_COMPRA
						AND ORDEN_COMPRA_PEDIDO = @PP_ORDEN_COMPRA_PEDIDO
						AND ORDEN_COMPRA_PEDIDO_ENTREGA = 1 -- PENDIENTE CARGAR DATO CORRECTO
						AND K_ITEM = @PP_K_ITEM

						IF ( @VP_N_MATERIAL_ESPERA_DISPOSICION IS NULL OR @VP_N_MATERIAL_ESPERA_DISPOSICION = 0 )
							RAISERROR ('ERROR: No se encontro el material en [INSPECCION_MATERIAL_ORDEN_ESPERA_DISPOSICION] ', 16, 1 ) --MENSAJE - Severity -State.
						
						-- //////////////////////SE VALIDA EL ESTATUS DEL MATERIAL EN LA TABLA DE DISPOCISION///////////////////////
						DECLARE @VP_K_ESTATUS_MATERIAL_DISPOSICION INT = 0
						DECLARE @VP_LOCACION_MATERIAL_DISPOSICION VARCHAR(5) = ''
						SELECT	@VP_K_ESTATUS_MATERIAL_DISPOSICION =  K_ESTATUS_MATERIAL_DISPOSICION,
								@VP_LOCACION_MATERIAL_DISPOSICION = LOCACION_DESTINO
						FROM [INSPECCION_MATERIAL_ORDEN_ESPERA_DISPOSICION]
						WHERE K_ORDEN_COMPRA = @PP_K_ORDEN_COMPRA
						AND ORDEN_COMPRA_PEDIDO = @PP_ORDEN_COMPRA_PEDIDO
						AND ORDEN_COMPRA_PEDIDO_ENTREGA = 1 -- PENDIENTE CARGAR DATO CORRECTO
						AND K_ITEM = @PP_K_ITEM

						IF @VP_K_ESTATUS_MATERIAL_DISPOSICION <> 0 -- EN ESPERA DE DISPOCISION
							BEGIN
								DECLARE @VP_ERROR VARCHAR(255) = 'ERROR: El material se proceso o esta siendo procesado por '+ @VP_LOCACION_MATERIAL_DISPOSICION
								RAISERROR (@VP_ERROR, 16, 1 ) --MENSAJE - Severity -State.
							END

						-- //////////////////////SE ACTUALIZA LA LOCACION A DONDE SE LE DARA DISPOCISION AL MATERIAL///////////////////////
						UPDATE [INSPECCION_MATERIAL_ORDEN_ESPERA_DISPOSICION]
							SET LOCACION_DESTINO = @VP_LOCACION_DESTINO
						WHERE K_ORDEN_COMPRA = @PP_K_ORDEN_COMPRA
						AND ORDEN_COMPRA_PEDIDO = @PP_ORDEN_COMPRA_PEDIDO
						AND ORDEN_COMPRA_PEDIDO_ENTREGA = 1 -- PENDIENTE CARGAR DATO CORRECTO
						AND K_ITEM = @PP_K_ITEM

						-- //////////////////////SE NOTIFICA A LOS RESPONSABLES DE LA LOCACION A DONDE VA EL MATERIAL///////////////////////
						EXECUTE [dbo].[PG_CONFIGURAR_CORREO_MATERIAL_INSPECCIONADO_DISPOSICION] @PP_K_SISTEMA_EXE, @PP_K_USUARIO_ACCION,
																								@PP_K_ORDEN_COMPRA, @PP_ORDEN_COMPRA_PEDIDO, 1,
																								@PP_K_ITEM, @VP_LOCACION_DESTINO

					END
				-- //////////////////////////////////////////////////////////////
			COMMIT TRANSACTION 
			END TRY
	
			BEGIN CATCH
				/* Ocurrió un error, deshacemos los cambios*/ 
				ROLLBACK TRANSACTION
				DECLARE @VP_ERROR_TRANS NVARCHAR(4000);
				SET @VP_ERROR_TRANS = ERROR_MESSAGE() 
				SET @VP_MENSAJE = 'ERROR: //TRANSAC. PG_UP_INSPECCION_MATERIAL_ORDEN_RESULTADO // ' + @VP_ERROR_TRANS
			END CATCH
		
		END

	-- // SECCION#3 ////////////////////////////////////////////////////////// MENSAJE DE SALIDA
	
	IF @VP_MENSAJE<>''
		BEGIN
		
		SET		@VP_MENSAJE = 'No es posible [Actualizar] la [INSPECCION_MATERIAL]: ' + @VP_MENSAJE 
		SET		@VP_MENSAJE = @VP_MENSAJE + ' ( '
		SET		@VP_MENSAJE = @VP_MENSAJE + '[#PART.'+ CONVERT(VARCHAR(10),@PP_K_ITEM) +']'
		SET		@VP_MENSAJE = @VP_MENSAJE + ' )'

		END
	
	SELECT	@VP_MENSAJE AS MENSAJE, @PP_K_ITEM AS CLAVE

	-- //////////////////////////////////////////////////////////////
GO


