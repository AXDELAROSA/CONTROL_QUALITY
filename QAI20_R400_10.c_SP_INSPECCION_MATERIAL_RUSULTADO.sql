*/


CREATE PROCEDURE [dbo].[PG_SK_INSPECCION_MATERIAL_ORDEN_A_MODIFICAR]
	@PP_K_SISTEMA_EXE				INT,
	@PP_K_USUARIO_ACCION			INT,
	-- ===========================
	@PP_K_INSPECCION_MATERIAL_ORDEN	INT
	-- ===========================
AS
	-- ///////////////////////////////////////////

	SELECT	TOP (5000)  
		INSPECCION_MATERIAL_ORDEN.K_INSPECCION_MATERIAL,
		INSPECCION_MATERIAL_ORDEN.K_ORDEN_COMPRA,
		INSPECCION_MATERIAL_ORDEN.ORDEN_COMPRA_PEDIDO,
		INSPECCION_MATERIAL_ORDEN.K_ITEM,
		VENDOR.D_VENDOR AS PROVEDOR,
		CUS_NO AS CLIENTE,
		-- ===========================
		PORCENTAJE_APROBATORIO,
		-- ===========================
		TOTAL_PORCENTAJE_ACUMULADO,
		-- ===========================
		PART_NUMBER_ITEM_VENDOR,
		PART_NUMBER_ITEM_PEARL,
		D_ITEM,
		(SELECT  TOP 1 QUANTITY_ORDER FROM COMPRAS_PRUEBAS.dbo.DETAILS_BPO_PEDIDO 
		WHERE K_HEADER_PURCHASE_ORDER = INSPECCION_MATERIAL_ORDEN.K_ORDEN_COMPRA
		AND K_ITEM = INSPECCION_MATERIAL_ORDEN.K_ITEM 
		AND K_ORDEN_COMPRA_PEDIDO = INSPECCION_MATERIAL_ORDEN.ORDEN_COMPRA_PEDIDO) 	AS QUANTITY
	FROM	INSPECCION_MATERIAL_ORDEN
	INNER JOIN	COMPRAS_PRUEBAS.dbo.ITEM		ON	INSPECCION_MATERIAL_ORDEN.K_ITEM=ITEM.K_ITEM

	INNER JOIN	COMPRAS_PRUEBAS.dbo.HEADER_BPO_PEDIDO ON INSPECCION_MATERIAL_ORDEN.K_ORDEN_COMPRA = COMPRAS_PRUEBAS.dbo.HEADER_BPO_PEDIDO.K_HEADER_PURCHASE_ORDER

	INNER JOIN	COMPRAS_PRUEBAS.dbo.VENDOR ON HEADER_BPO_PEDIDO.K_VENDOR = VENDOR.K_VENDOR

	INNER JOIN	ARCUSFIL_SQL ON HEADER_BPO_PEDIDO.K_CUSTOMER = ARCUSFIL_SQL.A4GLIdentity

	LEFT JOIN	[INSPECCION_MATERIAL_ORDEN_RESULTADO] ON HEADER_BPO_PEDIDO.K_HEADER_PURCHASE_ORDER = [INSPECCION_MATERIAL_ORDEN_RESULTADO].K_ORDEN_COMPRA
				AND	ITEM.K_ITEM = [INSPECCION_MATERIAL_ORDEN_RESULTADO].K_ITEM
	WHERE	INSPECCION_MATERIAL_ORDEN.K_INSPECCION_MATERIAL_ORDEN = @PP_K_INSPECCION_MATERIAL_ORDEN
	ORDER BY	K_INSPECCION_MATERIAL_ORDEN

	-- ////////////////////////////////////////////////
	-- ////////////////////////////////////////////////
GO





