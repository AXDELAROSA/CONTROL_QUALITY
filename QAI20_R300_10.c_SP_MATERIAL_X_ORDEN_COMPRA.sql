	INNER JOIN	COMPRAS_PRUEBAS.dbo.VENDOR ON HEADER_BPO_PEDIDO.K_VENDOR = VENDOR.K_VENDOR 
	-- =============================
	WHERE	K_ORDEN_COMPRA_PEDIDO = @PP_ORDEN_COMPRA_PEDIDO
	-- ////////////////////////////////////////////////
	-- ////////////////////////////////////////////////
GO


