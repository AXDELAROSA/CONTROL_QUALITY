IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[PG_SK_NUMERO_PARTE_X_K_DETALLE_ORDEN]') AND type in (N'P', N'PC'))
	DROP PROCEDURE [dbo].[PG_SK_NUMERO_PARTE_X_K_DETALLE_ORDEN]
