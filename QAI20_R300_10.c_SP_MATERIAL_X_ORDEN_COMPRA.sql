/* 
 EXEC	[dbo].[PG_LI_ITEM_PENDIENTE_INSPECCION] 0,0, 10 
*/
CREATE PROCEDURE [dbo].[PG_LI_ITEM_PENDIENTE_INSPECCION]
	@PP_K_SISTEMA_EXE				INT,
	@PP_K_USUARIO_ACCION			INT,
	-- ===========================
	@PP_K_STATUS_INVENTARIO			INT
	-- ===========================
AS

	DECLARE @VP_MENSAJE				VARCHAR(300) = ''
	-- ///////////////////////////////////////////
	-- SELECT * FROM STATUS_INVENTARIO
	SELECT	DISTINCT 
			K_ORDEN_COMPRA_PEDIDO,
			K_ENTREGA,
			ITEM.K_ITEM,
			PART_NUMBER_ITEM_PEARL,
			LTRIM(RTRIM(TRADEMARK_ITEM)) AS D_ITEM
	FROM	INVENTARIO
	INNER JOIN COMPRAS.dbo.ITEM AS ITEM ON ITEM.K_ITEM = INVENTARIO.K_ITEM
	WHERE K_STATUS_INVENTARIO = @PP_K_STATUS_INVENTARIO
	ORDER BY ITEM.K_ITEM
	-- ////////////////////////////////////////////////
	-- ////////////////////////////////////////////////
GO



