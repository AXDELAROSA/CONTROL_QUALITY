		BEGIN
			BEGIN TRANSACTION 
			BEGIN TRY
				DECLARE @VP_TIPO_INSPECCION_MATERIAL_LOG	INT = 3 -- APROBACION MANUAL
				
				-- ===========================
				IF @PP_ACEPTADO = 0
					SET @VP_TIPO_INSPECCION_MATERIAL_LOG = 4 -- RECHAZO MANUAL

				-- ===========================
				DECLARE @VP_ESTATUS_ACTUAL	INT = 0
				DECLARE @VP_K_ORDEN_COMPRA	INT = 0

				SELECT	@VP_ESTATUS_ACTUAL = ACEPTADO,
						@VP_K_ORDEN_COMPRA = K_ORDEN_COMPRA
				FROM	INSPECCION_MATERIAL_ORDEN_COMPRA_RESULTADO
				WHERE	K_ORDEN_COMPRA_PEDIDO = @PP_K_ORDEN_COMPRA_PEDIDO
				AND		K_ENTREGA = @PP_K_ENTREGA
				AND		K_ITEM = @PP_K_ITEM
				AND		LOTE_PEARL = @PP_LOTE_PEARL
											
				IF @VP_ESTATUS_ACTUAL IS NULL
					RAISERROR ('ERROR: No fue posible obtener el estatus actual de la inspección en [INSPECCION_MATERIAL_ORDEN_COMPRA_RESULTADO]', 16, 1 ) --MENSAJE - Severity -State. 
								
				-- ///////////////////SE VALIDA QUE EL ESTATUS ANTERIOR NO SEA IGUAL AL NUEVO////////////// 	
				IF @PP_ACEPTADO = 1 AND @VP_ESTATUS_ACTUAL = 1
					RAISERROR ('ERROR: El material ya se encuentra Aceptado en [INSPECCION_MATERIAL_ORDEN_COMPRA_RESULTADO] ', 16, 1 ) --MENSAJE - Severity -State. 
				-- ===========================

				
				IF @PP_ACEPTADO = 0 AND @VP_ESTATUS_ACTUAL = 0
					RAISERROR ('ERROR: El material ya se encuentra Rechazado en [INSPECCION_MATERIAL_ORDEN_COMPRA_RESULTADO] ', 16, 1 ) --MENSAJE - Severity -State. 

				-- ///////////////////SE OBTIENE EL USUARIO QUE AUTORIZO EL CAMBIO////////////// 
				DECLARE @VP_K_USUARIO_AUTORIZACION INT = 0
				SELECT  @VP_K_USUARIO_AUTORIZACION = K_USUARIO
				FROM	BD_GENERAL.DBO.[GRUPO_APROBADOR] 
				INNER	JOIN [BD_GENERAL].dbo.USUARIO_PEARL ON [GRUPO_APROBADOR].K_USUARIO = USUARIO_PEARL.K_USUARIO_PEARL
				WHERE	D_USUARIO_PEARL = @PP_D_USUARIO_AUTORIZACION	
				AND		D_GRUPO_APROBADOR = 'QA MADIFICAR INSPECCION MATERIAL'
				AND		K_ESTATUS_GRUPO_APROBADOR = 1 -- ACTIVO
				AND		K_TIPO_GRUPO_APROBADOR = 150 --  MODIFICAR INSPECCION MATERIAL QA

				IF @VP_K_USUARIO_AUTORIZACION IS NULL
					RAISERROR ('ERROR: No fue posible obtener usuario aprobador en [GRUPO_APROBADOR] ', 16, 1 ) --MENSAJE - Severity -State. 

				-- ///////////////////SE ACTUALIZA EL DATO//////////////////////////////////////////////////
				UPDATE INSPECCION_MATERIAL_ORDEN_COMPRA_RESULTADO
					SET [ACEPTADO]										= @PP_ACEPTADO,
						[K_USUARIO_ALTA]								= @PP_K_USUARIO_ACCION,
						[F_INSPECCION_MATERIAL_ORDEN_COMPRA_RESULTADO]	= GETDATE()	
				WHERE	K_ORDEN_COMPRA_PEDIDO = @PP_K_ORDEN_COMPRA_PEDIDO
				AND		K_ENTREGA = @PP_K_ENTREGA
				AND		K_ITEM = @PP_K_ITEM
				AND		LOTE_PEARL = @PP_LOTE_PEARL

				IF @@ROWCOUNT = 0
					RAISERROR ('ERROR: No fue posible actualizar el estatus de la inspección en [INSPECCION_MATERIAL_ORDEN_COMPRA_RESULTADO]', 16, 1 ) --MENSAJE - Severity -State.
				
				-- //////////////////////SE INGRESA EL LOG///////////////////////
				EXECUTE [dbo].[PG_IN_INSPECCION_MATERIAL_ORDEN_COMPRA_LOG]	@PP_K_SISTEMA_EXE, @PP_K_USUARIO_ACCION,
																			@VP_TIPO_INSPECCION_MATERIAL_LOG, @VP_K_ORDEN_COMPRA,
																			@PP_K_ORDEN_COMPRA_PEDIDO, @PP_K_ENTREGA, @PP_K_ITEM, @PP_LOTE_PEARL,
																			0, '', '', @VP_K_USUARIO_AUTORIZACION, @PP_COMENTARIO

				-- //////////////////////SE OBTIENE LA LOCACION MHI POR DEFAULT///////////////////////
				DECLARE @VP_K_LOCACION_ORIGEN INT =  6 -- MQU
				DECLARE @VP_K_LOCACION_DESTINO INT = 4 --MHI
				DECLARE @VP_LOCACION_DESTINO VARCHAR(5) = ''

				SELECT	@VP_LOCACION_DESTINO = LTRIM(RTRIM(LOC))
					FROM	imlocfil_sql 
				WHERE A4GLIdentity = @VP_K_LOCACION_DESTINO 
											
				-- //////////////////////SE OBTIENE LA LOCACION MQU SI EL RESULTADO DE LA INSPECCION ES RECHAZADO///////////////////////
				IF @PP_ACEPTADO = 0
					BEGIN
						SET @VP_K_LOCACION_ORIGEN =  4 --MHI
						SET @VP_K_LOCACION_DESTINO = 6 -- MQU

						SELECT	@VP_LOCACION_DESTINO = LTRIM(RTRIM(LOC))
						FROM	imlocfil_sql 
						WHERE A4GLIdentity = @VP_K_LOCACION_DESTINO
					END
					
				IF @VP_LOCACION_DESTINO IS NULL
					RAISERROR ('ERROR: No fue posible obtener la locacion en [imlocfil_sql] ', 16, 1 ) --MENSAJE - Severity -State.
					
				IF @VP_LOCACION_DESTINO NOT IN ('MHI','MQU')
					RAISERROR ('ERROR: Locacion no valida.', 16, 1 ) --MENSAJE - Severity -State.

				-- //////////////////////SE TRANSFIERE EL MATERIAL A LA LOCACION QUE CORRESPONDA MHI/MQU///////////////////////
				EXECUTE [dbo].[PG_IN_INVENTARIO_X_INSPECCION_MATERIAL]  @PP_K_SISTEMA_EXE, @PP_K_USUARIO_ACCION,
																		@PP_K_ORDEN_COMPRA_PEDIDO, @PP_K_ENTREGA, 
																		@PP_K_ITEM, @PP_LOTE_PEARL, @VP_K_LOCACION_ORIGEN, @VP_K_LOCACION_DESTINO

				-- //////////////////////SE NOTIFICA A LOS RESPONSABLES DE LA LOCACION A DONDE VA EL MATERIAL///////////////////////
				EXECUTE [dbo].[PG_CONFIGURAR_CORREO_MATERIAL_INSPECCIONADO_DISPOSICION] @PP_K_SISTEMA_EXE, @PP_K_USUARIO_ACCION,
																						@VP_K_ORDEN_COMPRA, @PP_K_ORDEN_COMPRA_PEDIDO,
																						@PP_K_ENTREGA, @PP_K_ITEM, @PP_LOTE_PEARL,
																						@VP_LOCACION_DESTINO
				-- //////////////////////////////////////////////////////////////
			COMMIT TRANSACTION 
			END TRY
	
			BEGIN CATCH
				/* Ocurrió un error, deshacemos los cambios*/ 
				ROLLBACK TRANSACTION
				DECLARE @VP_ERROR_TRANS NVARCHAR(4000);
				SET @VP_ERROR_TRANS = ERROR_MESSAGE() 
				SET @VP_MENSAJE = 'ERROR: //TRANSAC. PG_UP_INSPECCION_MATERIAL_ORDEN_RESULTADO_APROBACION // ' + @VP_ERROR_TRANS
			END CATCH
		
		END

	-- // SECCION#3 ////////////////////////////////////////////////////////// MENSAJE DE SALIDA
	
	IF @VP_MENSAJE<>''
		BEGIN
		
		SET		@VP_MENSAJE = 'No es posible [Actualizar] la [INSPECCION_MATERIAL]: ' + @VP_MENSAJE 
		SET		@VP_MENSAJE = @VP_MENSAJE + ' ( '
		SET		@VP_MENSAJE = @VP_MENSAJE + '[#ITEM.'+ CONVERT(VARCHAR(10),@PP_K_ITEM) +']'
		SET		@VP_MENSAJE = @VP_MENSAJE + ' )'

		END
	
	SELECT	@VP_MENSAJE AS MENSAJE, @PP_K_ITEM AS CLAVE

	-- //////////////////////////////////////////////////////////////
GO

