CREATE PROCEDURE [dbo].[PG_SK_INSPECCION_MATERIAL_ORDEN_COMPRA]
	@PP_K_SISTEMA_EXE				INT,
	@PP_K_USUARIO_ACCION			INT,
	-- ===========================
	@PP_K_ORDEN_COMPRA_PEDIDO		VARCHAR(50),
	@PP_K_ENTREGA					INT,
	@PP_K_ITEM						INT,
	@PP_LOTE_PEARL					INT,
	@PP_K_INSPECCION_MATERIAL		INT
	
AS

	DECLARE @VP_MENSAJE						VARCHAR(300) = ''
	-- ///////////////////////////////////////////

	SELECT	
			[INSPECCION_MATERIAL_ORDEN_COMPRA].*,
			INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL
	-- =============================	
	FROM	[INSPECCION_MATERIAL_ORDEN_COMPRA]
	INNER JOIN INSPECCION_MATERIAL ON [INSPECCION_MATERIAL_ORDEN_COMPRA].K_INSPECCION_MATERIAL = INSPECCION_MATERIAL.K_INSPECCION_MATERIAL
			AND [INSPECCION_MATERIAL_ORDEN_COMPRA].K_ITEM = INSPECCION_MATERIAL.K_ITEM
	INNER JOIN	TIPO_INSPECCION_MATERIAL ON INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL = TIPO_INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL
	-- =============================
	WHERE	K_ORDEN_COMPRA_PEDIDO = @PP_K_ORDEN_COMPRA_PEDIDO
	AND		K_ENTREGA = @PP_K_ENTREGA
	AND		[INSPECCION_MATERIAL_ORDEN_COMPRA].K_ITEM = @PP_K_ITEM
	AND		LOTE_PEARL = @PP_LOTE_PEARL
	AND		[INSPECCION_MATERIAL_ORDEN_COMPRA].K_INSPECCION_MATERIAL = @PP_K_INSPECCION_MATERIAL

	-- ////////////////////////////////////////////////
	-- ////////////////////////////////////////////////
GO




