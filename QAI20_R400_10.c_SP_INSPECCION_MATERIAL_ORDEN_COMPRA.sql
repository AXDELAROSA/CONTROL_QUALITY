			[INSPECCION_MATERIAL_ORDEN_COMPRA_RESULTADO].*,
			-- ===========================
		( CASE WHEN ACEPTADO = 1
				THEN 'ACEPTADO'
			WHEN ACEPTADO = 0 
				THEN 'RECHAZADO'
			ELSE 'PENDIENTE' END ) AS ESTATUS,
		-- ===========================
		PART_NUMBER_ITEM_PEARL
	-- =============================	
	FROM	[INSPECCION_MATERIAL_ORDEN_COMPRA_RESULTADO]
	INNER JOIN	COMPRAS.dbo.ITEM		ON	[INSPECCION_MATERIAL_ORDEN_COMPRA_RESULTADO].K_ITEM=ITEM.K_ITEM
