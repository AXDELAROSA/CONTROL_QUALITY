	AND			K_ENTREGA = @PP_K_ENTREGA
	AND			[INSPECCION_MATERIAL_ORDEN_COMPRA_RESULTADO].K_ITEM =  ( CASE WHEN @PP_K_ITEM = -1 THEN [INSPECCION_MATERIAL_ORDEN_COMPRA_RESULTADO].K_ITEM
																				ELSE @PP_K_ITEM END )
	AND			LOTE_PEARL = ( CASE WHEN @PP_LOTE_PEARL = -1 THEN LOTE_PEARL
									ELSE @PP_LOTE_PEARL END )
