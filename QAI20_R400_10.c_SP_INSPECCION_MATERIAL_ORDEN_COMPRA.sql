CREATE PROCEDURE [dbo].[PG_LI_AUTORIZAR_INSPECCION_MATERIAL_ORDEN_COMPRA]
	@PP_K_SISTEMA_EXE				INT,
	@PP_K_USUARIO_ACCION			INT,
	-- ===========================
	@PP_K_ORDEN_COMPRA_PEDIDO		VARCHAR(100),
	@PP_K_ENTREGA					INT,
	@PP_K_ITEM						INT,
	@PP_LOTE_PEARL					INT
	
AS

	DECLARE @VP_MENSAJE						VARCHAR(300) = ''
	-- ///////////////////////////////////////////

	SELECT	
			[INSPECCION_MATERIAL_ORDEN_COMPRA].*,
			INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL,
			INSPECCION_MATERIAL.INSPECCION,
			PART_NUMBER_ITEM_PEARL AS NUMERO_PARTE,
			LTRIM(RTRIM(TRADEMARK_ITEM)) AS D_ITEM,
			-- =============================	
			( CASE WHEN K_TIPO_INSPECCION_MATERIAL = 2
						THEN OPCION_1
				ELSE 'N/A'	END )	AS VALOR_MINIMO,
			-- =============================	
			( CASE WHEN K_TIPO_INSPECCION_MATERIAL = 2
						THEN OPCION_2
				ELSE 'N/A'	END )	AS VALOR_MAXIMO,
			-- =============================
			( CASE WHEN ACEPTADO = 1
						THEN 'SI'
				ELSE 'NO'	END )	AS ESTATUS,
			-- =============================
			BD_GENERAL.dbo.USUARIO_PEARL.D_USUARIO_PEARL,
			CONVERT(DATE, [INSPECCION_MATERIAL_ORDEN_COMPRA].F_CAMBIO) AS F_INSPECCION_ORDEN_COMPRA
			-- =============================	
	FROM	[INSPECCION_MATERIAL_ORDEN_COMPRA]
	INNER JOIN COMPRAS.dbo.ITEM ON [INSPECCION_MATERIAL_ORDEN_COMPRA].K_ITEM = ITEM.K_ITEM
	INNER JOIN INSPECCION_MATERIAL ON [INSPECCION_MATERIAL_ORDEN_COMPRA].K_INSPECCION_MATERIAL = INSPECCION_MATERIAL.K_INSPECCION_MATERIAL
			AND [INSPECCION_MATERIAL_ORDEN_COMPRA].K_ITEM = INSPECCION_MATERIAL.K_ITEM
	INNER JOIN	INSPECCION_OPCION ON INSPECCION_MATERIAL.K_INSPECCION_MATERIAL = INSPECCION_OPCION.K_INSPECCION_MATERIAL
	INNER JOIN	BD_GENERAL.dbo.USUARIO_PEARL ON	[INSPECCION_MATERIAL_ORDEN_COMPRA].K_USUARIO_CAMBIO = BD_GENERAL.dbo.USUARIO_PEARL.K_USUARIO_PEARL
	-- =============================
	WHERE	[INSPECCION_MATERIAL_ORDEN_COMPRA].K_ORDEN_COMPRA_PEDIDO = @PP_K_ORDEN_COMPRA_PEDIDO
	AND		[INSPECCION_MATERIAL_ORDEN_COMPRA].K_ENTREGA = @PP_K_ENTREGA
	AND		[INSPECCION_MATERIAL_ORDEN_COMPRA].K_ITEM = @PP_K_ITEM 
	AND		[INSPECCION_MATERIAL_ORDEN_COMPRA].LOTE_PEARL = @PP_LOTE_PEARL
	ORDER BY K_TIPO_INSPECCION_MATERIAL ASC
	-- ////////////////////////////////////////////////
	-- ////////////////////////////////////////////////
GO



