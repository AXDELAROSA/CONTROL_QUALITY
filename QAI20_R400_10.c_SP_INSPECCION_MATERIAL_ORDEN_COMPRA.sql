CREATE PROCEDURE [dbo].[PG_IN_UP_INSPECCION_MATERIAL_ORDEN_COMPRA]
	@PP_K_SISTEMA_EXE					INT,
	@PP_K_USUARIO_ACCION				INT,
	-- ===========================	
	@PP_K_ORDEN_COMPRA					INT,
	@PP_K_ORDEN_COMPRA_PEDIDO			VARCHAR(50),
	@PP_K_ENTREGA						INT,
	@PP_K_ITEM							INT,
	@PP_LOTE_PEARL						INT,
	@PP_K_INSPECCION_MATERIAL			INT,
	@PP_K_TIPO_INSPECCION_MATERIAL		INT,
	-- ===========================	
	@PP_RESULTADO_INSPECCION			VARCHAR(255),
	@PP_ACEPTADO						INT,
	@PP_COMENTARIO						VARCHAR(255),
	-- ============================	
	@PP_N_INSPECCION_CONFIGURADA		INT
AS			
	
	DECLARE @VP_MENSAJE		VARCHAR(300) = ''
	DECLARE @VP_K_INSPECCION_MATERIAL_ORDEN_COMPRA	INT = 0

	-- // SECCION#1 /////////////////////////////////////////////////////////// VALIDACIONES + REGLAS DE NEGOCIO 	
	--IF @VP_MENSAJE=''	
		--EXECUTE [dbo].[PG_RN_INSPECCION_MATERIAL_ORDEN_COMPRA_INSERT]	@PP_K_SISTEMA_EXE, @PP_K_USUARIO_ACCION,
		--													@PP_INSPECCION_PORCENTAJE, @PP_OPCION_1_PORCENTAJE,
		--													@PP_OPCION_2_PORCENTAJE, @PP_OPCION_3_PORCENTAJE,
		--													@PP_OPCION_4_PORCENTAJE, @PP_OPCION_5_PORCENTAJE,
		--													@OU_RESULTADO_VALIDACION = @VP_MENSAJE		OUTPUT

	-- // SECCION#2 ////////////////////////////////////////////////////////// ACCION A REALIZAR
	
	IF @VP_MENSAJE=''
		BEGIN
			BEGIN TRANSACTION 
			BEGIN TRY							
				
				-- ///////SI ES UNA INSPECCION TIPO 2 SE OBTIENE LOS PARAMETROS DE EVALUACION//////////////////
				IF @PP_K_TIPO_INSPECCION_MATERIAL = '2' --EVALUACION
					BEGIN
						DECLARE @VALOR_MINIMO DECIMAL(13,2) = 0
						DECLARE @VALOR_MAXIMO DECIMAL(13,2) = 0

						SELECT  @VALOR_MINIMO = CONVERT(DECIMAL(13,2),ISNULL(OPCION_1, 0)),
								@VALOR_MAXIMO = CONVERT(DECIMAL(13,2),ISNULL(OPCION_2, 0))
						FROM INSPECCION_OPCION
						WHERE [K_INSPECCION_MATERIAL] = @PP_K_INSPECCION_MATERIAL


						DECLARE @VP_VALOR_INSPECCION_DECIMAL DECIMAL(13,2) = CONVERT(DECIMAL(13,2), @PP_RESULTADO_INSPECCION)

						IF ( @VP_VALOR_INSPECCION_DECIMAL < @VALOR_MINIMO OR @VP_VALOR_INSPECCION_DECIMAL > @VALOR_MAXIMO )
							SET @PP_ACEPTADO = 0
					END

				-- ///////SE VERIFICA SI YA EXISTE LA ORDEN_COMPRA CON ESE NUMERO DE PARTE Y ESA INSPECCION EN INSPECCION_MATERIAL_ORDEN_COMPRA//////////////////
				DECLARE @VP_N_INSPECCION_MATERIAL_ORDEN_COMPRA  INT = 0

				SELECT	@VP_N_INSPECCION_MATERIAL_ORDEN_COMPRA = COUNT([K_INSPECCION_MATERIAL_ORDEN_COMPRA])
				FROM	INSPECCION_MATERIAL_ORDEN_COMPRA
				WHERE	K_ORDEN_COMPRA_PEDIDO = @PP_K_ORDEN_COMPRA_PEDIDO
				AND		K_ENTREGA = @PP_K_ENTREGA
				AND		K_ITEM = @PP_K_ITEM
				AND		LOTE_PEARL = @PP_LOTE_PEARL
				AND		K_INSPECCION_MATERIAL = @PP_K_INSPECCION_MATERIAL
				
				IF 	@VP_N_INSPECCION_MATERIAL_ORDEN_COMPRA IS NULL
					SET @VP_N_INSPECCION_MATERIAL_ORDEN_COMPRA = 0

				-- ///////SI NO EXISTE UNA INSPECCION CON ESA ORDEN_COMPRA, NUMERO DE PARTE E INSPECCION SE INGRESA EL REGISTRO SI NO SE ACTUALIZA//////////////////
				IF @VP_N_INSPECCION_MATERIAL_ORDEN_COMPRA = 0
					BEGIN
						EXECUTE BD_GENERAL.dbo.[PG_SK_CATALOGO_K_MAX_GET]	@PP_K_SISTEMA_EXE,
																			'DATA_02', 'INSPECCION_MATERIAL_ORDEN_COMPRA', 'K_INSPECCION_MATERIAL_ORDEN_COMPRA',
																			@OU_K_TABLA_DISPONIBLE = @VP_K_INSPECCION_MATERIAL_ORDEN_COMPRA	OUTPUT

						-- ///////SE INSERTA LA INSPECCION DEL MATERIAL///////////////////////////////////////////////////////
						INSERT INTO [INSPECCION_MATERIAL_ORDEN_COMPRA]
							(	[K_INSPECCION_MATERIAL_ORDEN_COMPRA],
								-- ===========================
								[K_ORDEN_COMPRA],
								[K_ORDEN_COMPRA_PEDIDO],
								[K_ENTREGA],
								[K_ITEM],
								[LOTE_PEARL],
								[K_INSPECCION_MATERIAL],
								-- ===========================
								[OPCION_SELECCIONADA],
								[ACEPTADO],
								[COMENTARIO],
								[F_ORDEN_COMPRA_INSPECCION_MATERIAL],
								-- ===========================
								[K_USUARIO_ALTA], [F_ALTA], [K_USUARIO_CAMBIO], [F_CAMBIO],
								[L_BORRADO], [K_USUARIO_BAJA], [F_BAJA]  )
						VALUES	
							(	@VP_K_INSPECCION_MATERIAL_ORDEN_COMPRA,
								-- ===========================	
								@PP_K_ORDEN_COMPRA,			
								@PP_K_ORDEN_COMPRA_PEDIDO,	
								@PP_K_ENTREGA,	
								@PP_K_ITEM,				
								@PP_LOTE_PEARL,
								@PP_K_INSPECCION_MATERIAL,
								-- ===========================	
								@PP_RESULTADO_INSPECCION,
								@PP_ACEPTADO,		
								@PP_COMENTARIO,					
								GETDATE(),
								-- ===========================
								@PP_K_USUARIO_ACCION, GETDATE(), @PP_K_USUARIO_ACCION, GETDATE(),
								0, NULL, NULL )

						IF @@ROWCOUNT = 0
							RAISERROR ('ERROR: No fue posible ingresar el registro en [INSPECCION_MATERIAL_ORDEN_COMPRA] ', 16, 1 ) --MENSAJE - Severity -State.
							--=====================================================
					END
				ELSE
					BEGIN
						-- ///////SI ACTUALIZA LA INSPECCION CON ESA ORDEN_COMPRA, NUMERO DE PARTE E INSPECCION EN [INSPECCION_MATERIAL_ORDEN_COMPRA]//////////////////
						UPDATE [INSPECCION_MATERIAL_ORDEN_COMPRA]
							SET	[OPCION_SELECCIONADA]					= @PP_RESULTADO_INSPECCION,
								[COMENTARIO]							= @PP_COMENTARIO,
								[ACEPTADO]								= @PP_ACEPTADO,
								[F_ORDEN_COMPRA_INSPECCION_MATERIAL]	= GETDATE(),
								F_CAMBIO								= GETDATE(),
								K_USUARIO_CAMBIO						= @PP_K_USUARIO_ACCION
						WHERE	K_ORDEN_COMPRA_PEDIDO = @PP_K_ORDEN_COMPRA_PEDIDO
						AND		K_ENTREGA = @PP_K_ENTREGA
						AND		K_ITEM = @PP_K_ITEM
						AND		LOTE_PEARL = @PP_LOTE_PEARL
						AND		K_INSPECCION_MATERIAL = @PP_K_INSPECCION_MATERIAL
						
						IF @@ROWCOUNT = 0
							RAISERROR ('ERROR: No fue posible actualizar la inspección en [INSPECCION_MATERIAL_ORDEN_COMPRA] ', 16, 1 ) --MENSAJE - Severity -State.

					END

				-- ///////SE OBTIENE EL NUMERO DE INSPECCIONES REALIZADAS//////////////////
				DECLARE @VP_N_INSPECCION_REALIZADA		INT = 0
				SELECT	@VP_N_INSPECCION_REALIZADA = COUNT([K_INSPECCION_MATERIAL_ORDEN_COMPRA])
				FROM	INSPECCION_MATERIAL_ORDEN_COMPRA
				WHERE	K_ORDEN_COMPRA_PEDIDO = @PP_K_ORDEN_COMPRA_PEDIDO
				AND		K_ENTREGA = @PP_K_ENTREGA
				AND		K_ITEM = @PP_K_ITEM
				AND		LOTE_PEARL = @PP_LOTE_PEARL

				IF @VP_N_INSPECCION_REALIZADA IS NULL
					SET @VP_N_INSPECCION_REALIZADA = 0

				-- /////// SI EL NUMERO DE INSPECCIONES CONFIGURADAS SON IGUALES A LAS REALIZADAS SE CIERRA LA INSPECCION DEL MATERIAL//////////////////
				IF @PP_N_INSPECCION_CONFIGURADA = @VP_N_INSPECCION_REALIZADA
					BEGIN
						-- ///////SE VERIFICA SI HAY UNA INSPECCION RECHAZADA PARA RECHAZAR LA INSPECCION COMPLETA///////////////////////////////////////////////////////
						DECLARE @VP_N_INSPECCION_RECHAZADA	INT = 0
						SELECT	@VP_N_INSPECCION_RECHAZADA	=	COUNT([K_INSPECCION_MATERIAL_ORDEN_COMPRA])
						FROM	INSPECCION_MATERIAL_ORDEN_COMPRA
						WHERE	K_ORDEN_COMPRA_PEDIDO = @PP_K_ORDEN_COMPRA_PEDIDO
						AND		K_ENTREGA = @PP_K_ENTREGA
						AND		K_ITEM = @PP_K_ITEM
