CREATE PROCEDURE [dbo].[PG_SK_INSPECCION_MATERIAL_ORDEN_COMPRA_A_MODIFICAR]
	@PP_K_SISTEMA_EXE				INT,
	@PP_K_USUARIO_ACCION			INT,
	-- ===========================
	@PP_K_INSPECCION_MATERIAL_ORDEN_COMPRA	INT
	-- ===========================
AS
	-- ///////////////////////////////////////////

	SELECT	TOP (5000)  
		INSPECCION_MATERIAL_ORDEN_COMPRA.K_INSPECCION_MATERIAL,
		INSPECCION_MATERIAL_ORDEN_COMPRA.K_ORDEN_COMPRA,
		INSPECCION_MATERIAL_ORDEN_COMPRA.K_ORDEN_COMPRA_PEDIDO,
		INSPECCION_MATERIAL_ORDEN_COMPRA.K_ENTREGA,
		INSPECCION_MATERIAL_ORDEN_COMPRA.K_ITEM,
		LTRIM(RTRIM(TRADEMARK_ITEM)) AS D_ITEM,
		INSPECCION_MATERIAL_ORDEN_COMPRA.LOTE_PEARL,
		VENDOR.D_VENDOR AS PROVEDOR,
		CUS_NO AS CLIENTE,
		-- ===========================
		PART_NUMBER_ITEM_VENDOR,
		PART_NUMBER_ITEM_PEARL,
		D_ITEM,
		-- ===========================	-- ===========================
		(SELECT SUM(RECIBO.QUANTITY_RECEIVED) 
		FROM COMPRAS.dbo.DETAILS_BPO_RECIBO  RECIBO
		WHERE RECIBO.K_ORDEN_COMPRA_PEDIDO = INSPECCION_MATERIAL_ORDEN_COMPRA.K_ORDEN_COMPRA_PEDIDO
		AND	RECIBO.K_ENTREGA = INSPECCION_MATERIAL_ORDEN_COMPRA.K_ENTREGA
		AND	RECIBO.K_ITEM = INSPECCION_MATERIAL_ORDEN_COMPRA.K_ITEM
		AND	RECIBO.LOTE_PEARL = INSPECCION_MATERIAL_ORDEN_COMPRA.LOTE_PEARL ) AS QUANTITY
	FROM	INSPECCION_MATERIAL_ORDEN_COMPRA
	INNER JOIN	COMPRAS.dbo.ITEM		ON	INSPECCION_MATERIAL_ORDEN_COMPRA.K_ITEM=ITEM.K_ITEM
		
	INNER JOIN	COMPRAS.dbo.HEADER_BPO_PEDIDO ON INSPECCION_MATERIAL_ORDEN_COMPRA.K_ORDEN_COMPRA_PEDIDO = COMPRAS.dbo.HEADER_BPO_PEDIDO.K_ORDEN_COMPRA_PEDIDO
	INNER JOIN	COMPRAS.dbo.VENDOR ON HEADER_BPO_PEDIDO.K_VENDOR = VENDOR.K_VENDOR

	INNER JOIN	COMPRAS.dbo.DETAILS_BLANKET_PURCHASE_ORDER  ON	INSPECCION_MATERIAL_ORDEN_COMPRA.K_ORDEN_COMPRA = DETAILS_BLANKET_PURCHASE_ORDER.K_HEADER_PURCHASE_ORDER
		
	INNER JOIN	ARCUSFIL_SQL ON DETAILS_BLANKET_PURCHASE_ORDER.K_CUSTOMER = ARCUSFIL_SQL.A4GLIdentity

	WHERE	INSPECCION_MATERIAL_ORDEN_COMPRA.K_INSPECCION_MATERIAL_ORDEN_COMPRA = @PP_K_INSPECCION_MATERIAL_ORDEN_COMPRA
	ORDER BY	K_INSPECCION_MATERIAL_ORDEN_COMPRA

	-- ////////////////////////////////////////////////
	-- ////////////////////////////////////////////////
GO





