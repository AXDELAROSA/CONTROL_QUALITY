*/

CREATE PROCEDURE [dbo].[PG_SK_INSPECCION_LOTE_PIEL_RESULTADO_LOG]
	@PP_K_SISTEMA_EXE				INT,
	@PP_K_USUARIO_ACCION			INT,
	-- ===========================
	@PP_K_LOTE_IMPORTACION			INT,
	@PP_K_ITEM						INT,
	@PP_LOTE						INT
	
AS

	-- ///////////////////////////////////////////
	SELECT	
			[INSPECCION_LOTE_PIEL_RESULTADO_LOG].*,
			D_USUARIO_PEARL				AS D_USUARIO_CAMBIO,
			D_ESTATUS_INSPECCION_LOTE_PIEL,
			ISNULL(INSPECCION, 'N/A') AS INSPECCION
	-- =============================	
	FROM	[INSPECCION_LOTE_PIEL_RESULTADO_LOG] (NOLOCK)
	LEFT JOIN INSPECCION_MATERIAL (NOLOCK) ON INSPECCION_MATERIAL.K_INSPECCION_MATERIAL = [INSPECCION_LOTE_PIEL_RESULTADO_LOG].K_INSPECCION_MATERIAL
	INNER JOIN BD_GENERAL.dbo.USUARIO_PEARL (NOLOCK) ON [INSPECCION_LOTE_PIEL_RESULTADO_LOG].K_USUARIO_CAMBIO = BD_GENERAL.dbo.USUARIO_PEARL.K_USUARIO_PEARL
	INNER JOIN ESTATUS_INSPECCION_LOTE_PIEL (NOLOCK) ON ESTATUS_INSPECCION_LOTE_PIEL.K_ESTATUS_INSPECCION_LOTE_PIEL = [INSPECCION_LOTE_PIEL_RESULTADO_LOG].K_ESTATUS_INSPECCION_LOTE_PIEL
	-- =============================
	WHERE	[K_IMPORTACION_LOTE_PIEL] = @PP_K_LOTE_IMPORTACION
	AND		[INSPECCION_LOTE_PIEL_RESULTADO_LOG].K_ITEM = @PP_K_ITEM
	AND		LOTE = @PP_LOTE

	-- ////////////////////////////////////////////////
	-- ////////////////////////////////////////////////
GO

