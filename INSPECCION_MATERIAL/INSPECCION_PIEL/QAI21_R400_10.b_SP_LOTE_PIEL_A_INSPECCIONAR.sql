CREATE PROCEDURE [dbo].[PG_LI_INCINSP_SQL]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO_ACCION		INT,
	-- ===========================
	@PP_BUSCAR					VARCHAR(200),
	-- ===========================
	@PP_F_INICIO				DATE,
	@PP_F_FIN					DATE,
	@PP_COLOR					VARCHAR(50),
	@PP_ESTATUS					VARCHAR(50),
	@PP_DEFECTO					VARCHAR(50)
AS

	-- ///////////////////////////////////////////
	DECLARE @TBL_INSPECCION_LOTE_PIEL TABLE(
		K_INSPECCION_LOTE		INT,
		FECHA					DATE,
		PACKING_NO				VARCHAR(50),
		COLOR					VARCHAR(100),
		D_COLOR					VARCHAR(150),
		K_ITEM					VARCHAR(10),
		LOTE					VARCHAR(50),
		CANTIDAD_LOTE			INT,
		CANTIDAD_MUESTRA		INT,
		THICKNESS				VARCHAR(10),
		DEFECTO					VARCHAR(255),
		ESTATUS					VARCHAR(50),
		F_INSPECCION			VARCHAR(50),
		USUARIO_INSPECCION		VARCHAR(50)
	) 

	-- ///////////////////////////////////////////
	INSERT INTO @TBL_INSPECCION_LOTE_PIEL
		SELECT	ID					AS K_INSPECCION_LOTE,
				[dbo].[CONVERT_INT_TO_DATE]([Date])	AS FECHA,
				PACKING_NO,
				LTRIM(RTRIM(Description)) AS COLOR,
				LTRIM(RTRIM(item_desc_1)) AS D_COLOR,
				upc_cd				AS K_ITEM,
				LTRIM(RTRIM(Lot))	AS LOTE,
				IncInsp_sql.Lot_size AS CANTIDAD_LOTE,
				Sample_size			AS CANTIDAD_MUESTRA,
				Thickness			AS THICKNESS,
				Defecto				AS DEFECTO,
				( CASE WHEN STATUS = 'C' AND [K_ESTATUS_INSPECCION_LOTE_PIEL] IS NULL THEN 'ACEPTADO'
					WHEN STATUS <> 'C' AND [K_ESTATUS_INSPECCION_LOTE_PIEL] IS NULL THEN 'PENDIENTE'
					WHEN [K_ESTATUS_INSPECCION_LOTE_PIEL] = 1 THEN 'INSPECCIONADO'
					WHEN [K_ESTATUS_INSPECCION_LOTE_PIEL] = 2 THEN 'REVISION'
					WHEN [K_ESTATUS_INSPECCION_LOTE_PIEL] = 3 THEN 'ACEPTADO'
					WHEN [K_ESTATUS_INSPECCION_LOTE_PIEL] = 4 THEN 'RECHAZADO'
				END ) AS ESTATUS,
				-- ===========================
			(CASE WHEN F_INSPECCION_LOTE_PIEL_RESULTADO IS NULL THEN '-'
				ELSE CONVERT(VARCHAR(10),F_INSPECCION_LOTE_PIEL_RESULTADO, 5) END) AS F_INSPECCION,
			-- =============================	
			(CASE WHEN [INSPECCION_LOTE_PIEL_RESULTADO].K_USUARIO_ALTA IS NULL THEN '-'
				ELSE (	SELECT D_USUARIO_PEARL 
						FROM BD_GENERAL.DBO.USUARIO_PEARL 
						WHERE K_USUARIO_PEARL =  [INSPECCION_LOTE_PIEL_RESULTADO].K_USUARIO_ALTA ) END ) AS USUARIO_INSPECCION
		FROM	IncInsp_sql (NOLOCK)
		INNER JOIN	IMITMIDX_SQL (NOLOCK) ON  LTRIM(RTRIM(ITEM_NO)) =  [Description]
		LEFT JOIN	[INSPECCION_LOTE_PIEL_RESULTADO] (NOLOCK) ON K_IMPORTACION_LOTE_PIEL = ID 
				AND	RIGHT('000000' + LTRIM(RTRIM(LOTE)), 6)  = LTRIM(RTRIM(Lot))
				AND K_ITEM = upc_cd
		WHERE 	( LOT				LIKE '%'+@PP_BUSCAR+'%'
				OR	PACKING_NO		LIKE '%'+@PP_BUSCAR+'%'
				OR	ID		LIKE '%'+@PP_BUSCAR+'%' )
		-- =============================
		AND		[DATE] >= [dbo].[CONVERT_DATE_TO_INT](@PP_F_INICIO, 'yyyyMMdd')
		AND		[DATE] <= [dbo].[CONVERT_DATE_TO_INT](@PP_F_FIN, 'yyyyMMdd') 	
		AND		( @PP_COLOR = '( TODOS )'		OR	LTRIM(RTRIM([Description])) = @PP_COLOR  )
		AND		( @PP_DEFECTO = '( TODOS )'		OR	LTRIM(RTRIM(Defecto)) = @PP_DEFECTO )
		ORDER BY	[DATE]	DESC

	SELECT	K_INSPECCION_LOTE,
			FECHA,
			PACKING_NO,
			COLOR,				
			D_COLOR,				
			K_ITEM,			
			LOTE,			
			CANTIDAD_LOTE,		
			CANTIDAD_MUESTRA,	
			THICKNESS,			
			DEFECTO,				
			ESTATUS,				
			F_INSPECCION,		
			USUARIO_INSPECCION	
	FROM @TBL_INSPECCION_LOTE_PIEL
	WHERE ( @PP_ESTATUS = '( TODOS )'		OR	ESTATUS = @PP_ESTATUS )
	ORDER BY FECHA ASC
	
	-- ////////////////////////////////////////////////
	-- ////////////////////////////////////////////////
GO



