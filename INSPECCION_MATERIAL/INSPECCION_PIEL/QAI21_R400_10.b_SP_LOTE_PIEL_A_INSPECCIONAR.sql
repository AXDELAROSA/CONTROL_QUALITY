	-- ===========================
	@PP_K_INSPECCION_LOTE			INT
AS

	-- //////////SE VALIDA SI EXISTE LA INSPECCION TIPO GROOS/////////////////////////////////
	DECLARE @VP_N_INSPECCION_GROSS INT = 0

	SELECT @VP_N_INSPECCION_GROSS = COUNT([K_INSPECCION_LOTE_PIEL]) 
	FROM [INSPECCION_LOTE_PIEL] (NOLOCK)
	INNER JOIN INSPECCION_MATERIAL (NOLOCK) ON  INSPECCION_MATERIAL.K_INSPECCION_MATERIAL = [INSPECCION_LOTE_PIEL].K_INSPECCION_MATERIAL
	WHERE K_IMPORTACION_LOTE_PIEL =  @PP_K_INSPECCION_LOTE
	AND K_TIPO_INSPECCION_MATERIAL = 5 --# GROSS

	IF @VP_N_INSPECCION_GROSS IS NULL
		SET @VP_N_INSPECCION_GROSS = 0

	-- //////////SE VALIDA SI EXISTE LA INSPECCION TIPO SUAVIDAD/////////////////////////////////
	DECLARE @VP_N_INSPECCION_SUAVIDAD INT = 0
	SELECT @VP_N_INSPECCION_SUAVIDAD = COUNT([K_INSPECCION_LOTE_PIEL]) 
	FROM [INSPECCION_LOTE_PIEL] (NOLOCK)
	INNER JOIN INSPECCION_MATERIAL (NOLOCK) ON  INSPECCION_MATERIAL.K_INSPECCION_MATERIAL = [INSPECCION_LOTE_PIEL].K_INSPECCION_MATERIAL
	WHERE K_IMPORTACION_LOTE_PIEL =  @PP_K_INSPECCION_LOTE
	AND K_TIPO_INSPECCION_MATERIAL = 6 --# SUAVIDAD

	IF @VP_N_INSPECCION_SUAVIDAD IS NULL
		SET @VP_N_INSPECCION_SUAVIDAD = 0

	-- ///////////////////////////////////////////
	SELECT	ID						AS K_INSPECCION_LOTE,
			[dbo].[CONVERT_INT_TO_DATE]([Date])	AS FECHA,
			PACKING_NO,
			LTRIM(RTRIM(Lot))		AS LOTE,
			LTRIM(RTRIM(Description)) AS COLOR,
			LTRIM(RTRIM(item_desc_1)) AS D_COLOR,
			upc_cd					AS K_ITEM,
			IncInsp_sql.Lot_size	AS CANTIDAD_LOTE,
			Sample_size				AS CANTIDAD_MUESTRA,
			Thickness				AS THICKNESS,
			Defecto					AS DEFECTO,
			-- ===========================
			( CASE WHEN STATUS = 'C' AND [K_ESTATUS_INSPECCION_LOTE_PIEL] IS NULL THEN 'ACEPTADO'
					WHEN STATUS <> 'C' AND [K_ESTATUS_INSPECCION_LOTE_PIEL] IS NULL THEN 'PENDIENTE'
					WHEN [K_ESTATUS_INSPECCION_LOTE_PIEL] = 1 THEN 'INSPECCIONADO'
					WHEN [K_ESTATUS_INSPECCION_LOTE_PIEL] = 2 THEN 'REVISION'
					WHEN [K_ESTATUS_INSPECCION_LOTE_PIEL] = 3 THEN 'ACEPTADO'
					WHEN [K_ESTATUS_INSPECCION_LOTE_PIEL] = 4 THEN 'RECHAZADO'
				END ) AS ESTATUS,
			-- ===========================
			@VP_N_INSPECCION_GROSS		AS N_INSPECCION_GROSS,
			@VP_N_INSPECCION_SUAVIDAD	AS N_INSPECCION_SUAVIDAD
	FROM	IncInsp_sql (NOLOCK)
	INNER JOIN IMITMIDX_SQL (NOLOCK) ON  LTRIM(RTRIM(ITEM_NO)) =  [Description]
	LEFT JOIN	[INSPECCION_LOTE_PIEL_RESULTADO] (NOLOCK) ON K_IMPORTACION_LOTE_PIEL = ID 
				AND	RIGHT('000000' + LTRIM(RTRIM(LOTE)), 6) = LTRIM(RTRIM(Lot))
				AND K_ITEM = upc_cd
	WHERE 	ID = @PP_K_INSPECCION_LOTE

	
	-- ////////////////////////////////////////////////
	-- ////////////////////////////////////////////////
GO




