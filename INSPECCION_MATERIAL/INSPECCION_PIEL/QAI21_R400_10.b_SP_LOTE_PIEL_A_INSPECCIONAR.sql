CREATE PROCEDURE [dbo].[PG_SK_INSPECCION_PIEL_X_LOTE_CON_OPCION]
	@PP_K_SISTEMA_EXE				INT,
	@PP_K_USUARIO_ACCION			INT,
	-- ===========================
	@PP_K_LOTE_IMPORTACION			INT,
	@PP_K_ITEM						INT,
	@PP_LOTE						INT,
	@PP_K_INSPECCION_MATERIAL		INT,
	@PP_PRIMER_INSPECCION			INT, --#0 Cuando se abre ficha, #1 cuando se oprime adelande o atras 
	@PP_TIPO_MOVIMIENTO				INT --#0 ANTERIOR, #1 SIGUIENTE
AS

	-- ////////////////////////////////////////////////
	DECLARE @VP_POSICION_INSPECCION INT = 0
	DECLARE @VP_N_INSPECCION_X_ITEM INT = 0
	SELECT @VP_N_INSPECCION_X_ITEM = COUNT(K_INSPECCION_MATERIAL)
	FROM INSPECCION_MATERIAL (NOLOCK)
	WHERE K_ITEM = @PP_K_ITEM
	AND		INSPECCION_MATERIAL.K_ESTATUS_INSPECCION_MATERIAL = 1 -- ACTIVA

	IF @VP_N_INSPECCION_X_ITEM IS NULL
		SET @VP_N_INSPECCION_X_ITEM = 0
		
	-- ////////////////////////////////////////////////
	IF @PP_TIPO_MOVIMIENTO = 1 -- SIGUIENTE
		SELECT	TOP 1
				INSPECCION_MATERIAL.*,
				INSPECCION_OPCION.*,
				D_ESTATUS_INSPECCION_MATERIAL, S_ESTATUS_INSPECCION_MATERIAL, 
				D_TIPO_INSPECCION_MATERIAL, S_TIPO_INSPECCION_MATERIAL, 
				K_USUARIO_PEARL AS D_USUARIO_CAMBIO,
				ISNULL(OPCION_SELECCIONADA, '') AS OPCION_SELECCIONADA,
				ISNULL(ACEPTADO, '') AS ACEPTADO,
				ISNULL(COMENTARIO, '') AS COMENTARIO,
				@VP_N_INSPECCION_X_ITEM AS TOTAL_INSPECCION,
				@VP_POSICION_INSPECCION	AS POSICION_INSPECCION
				-- =============================	
		FROM	INSPECCION_MATERIAL (NOLOCK)
				-- =============================
				INNER JOIN ESTATUS_INSPECCION_MATERIAL (NOLOCK) ON INSPECCION_MATERIAL.K_ESTATUS_INSPECCION_MATERIAL = ESTATUS_INSPECCION_MATERIAL.K_ESTATUS_INSPECCION_MATERIAL
				INNER JOIN TIPO_INSPECCION_MATERIAL (NOLOCK) ON INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL = TIPO_INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL
				INNER JOIN INSPECCION_OPCION (NOLOCK) ON INSPECCION_MATERIAL.K_INSPECCION_MATERIAL = INSPECCION_OPCION.K_INSPECCION_MATERIAL
				INNER JOIN BD_GENERAL.dbo.USUARIO_PEARL (NOLOCK) ON INSPECCION_MATERIAL.K_USUARIO_CAMBIO = BD_GENERAL.dbo.USUARIO_PEARL.K_USUARIO_PEARL
				-- =============================
				LEFT  JOIN INSPECCION_LOTE_PIEL (NOLOCK) ON INSPECCION_LOTE_PIEL.K_INSPECCION_MATERIAL = INSPECCION_MATERIAL.K_INSPECCION_MATERIAL
						AND INSPECCION_LOTE_PIEL.K_ITEM = INSPECCION_MATERIAL.K_ITEM
						AND	INSPECCION_LOTE_PIEL.K_IMPORTACION_LOTE_PIEL = @PP_K_LOTE_IMPORTACION
						AND INSPECCION_LOTE_PIEL.LOTE = @PP_LOTE
				-- =============================
		WHERE	INSPECCION_MATERIAL.K_ITEM=@PP_K_ITEM
		AND		INSPECCION_MATERIAL.K_INSPECCION_MATERIAL > ( CASE	WHEN @PP_PRIMER_INSPECCION = 1	THEN 0
															ELSE @PP_K_INSPECCION_MATERIAL END )
		-- =============================
		AND		ESTATUS_INSPECCION_MATERIAL.K_ESTATUS_INSPECCION_MATERIAL = 1 -- ACTIVA
		-- =============================
		ORDER BY INSPECCION_MATERIAL.K_INSPECCION_MATERIAL ASC

	-- ////////////////////////////////////////////////
	IF @PP_TIPO_MOVIMIENTO = 0 -- ANTERIOR
		SELECT	TOP 1
				INSPECCION_MATERIAL.*,
				INSPECCION_OPCION.*,
				D_ESTATUS_INSPECCION_MATERIAL, S_ESTATUS_INSPECCION_MATERIAL, 
				D_TIPO_INSPECCION_MATERIAL, S_TIPO_INSPECCION_MATERIAL, 
				K_USUARIO_PEARL AS D_USUARIO_CAMBIO,
				ISNULL(OPCION_SELECCIONADA, '') AS OPCION_SELECCIONADA,
				ISNULL(ACEPTADO, '') AS ACEPTADO,
				ISNULL(COMENTARIO, '') AS COMENTARIO,
				@VP_N_INSPECCION_X_ITEM AS TOTAL_INSPECCION,
				@VP_POSICION_INSPECCION	AS POSICION_INSPECCION
				-- =============================	
		FROM	INSPECCION_MATERIAL (NOLOCK)
				-- =============================
				INNER JOIN ESTATUS_INSPECCION_MATERIAL (NOLOCK) ON INSPECCION_MATERIAL.K_ESTATUS_INSPECCION_MATERIAL = ESTATUS_INSPECCION_MATERIAL.K_ESTATUS_INSPECCION_MATERIAL
				INNER JOIN TIPO_INSPECCION_MATERIAL (NOLOCK) ON INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL = TIPO_INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL
				INNER JOIN INSPECCION_OPCION (NOLOCK) ON INSPECCION_MATERIAL.K_INSPECCION_MATERIAL = INSPECCION_OPCION.K_INSPECCION_MATERIAL
				INNER JOIN BD_GENERAL.dbo.USUARIO_PEARL (NOLOCK) ON INSPECCION_MATERIAL.K_USUARIO_CAMBIO = BD_GENERAL.dbo.USUARIO_PEARL.K_USUARIO_PEARL
				-- =============================
				LEFT  JOIN INSPECCION_LOTE_PIEL (NOLOCK) ON INSPECCION_LOTE_PIEL.K_INSPECCION_MATERIAL = INSPECCION_MATERIAL.K_INSPECCION_MATERIAL
						AND INSPECCION_LOTE_PIEL.K_ITEM = INSPECCION_MATERIAL.K_ITEM
						AND	INSPECCION_LOTE_PIEL.K_IMPORTACION_LOTE_PIEL = @PP_K_LOTE_IMPORTACION
						AND INSPECCION_LOTE_PIEL.LOTE = @PP_LOTE
				-- =============================
		WHERE	INSPECCION_MATERIAL.K_ITEM=@PP_K_ITEM
		AND		INSPECCION_MATERIAL.K_INSPECCION_MATERIAL < ( CASE	WHEN @PP_PRIMER_INSPECCION = 1	THEN 0
																	ELSE @PP_K_INSPECCION_MATERIAL END )
		-- =============================
		AND		ESTATUS_INSPECCION_MATERIAL.K_ESTATUS_INSPECCION_MATERIAL = 1 -- ACTIVA
		-- =============================
		ORDER BY INSPECCION_MATERIAL.K_INSPECCION_MATERIAL DESC


		-- ////////////////////////////////////////////////
	IF @PP_TIPO_MOVIMIENTO = 2 -- PARA ACTUALIZAR INSPECCION
		BEGIN
			SELECT @VP_POSICION_INSPECCION = COUNT(K_INSPECCION_MATERIAL) 
			FROM INSPECCION_MATERIAL (NOLOCK)
			WHERE K_ITEM = @PP_K_ITEM AND K_ESTATUS_INSPECCION_MATERIAL = 1 
			AND K_INSPECCION_MATERIAL <= @PP_K_INSPECCION_MATERIAL
						
			SELECT	TOP 1
					INSPECCION_MATERIAL.*,
					INSPECCION_OPCION.*,
					D_ESTATUS_INSPECCION_MATERIAL, S_ESTATUS_INSPECCION_MATERIAL, 
					D_TIPO_INSPECCION_MATERIAL, S_TIPO_INSPECCION_MATERIAL, 
					K_USUARIO_PEARL AS D_USUARIO_CAMBIO,
					ISNULL(OPCION_SELECCIONADA, '') AS OPCION_SELECCIONADA,
					ISNULL(ACEPTADO, '') AS ACEPTADO,
					ISNULL(COMENTARIO, '') AS COMENTARIO,
					@VP_N_INSPECCION_X_ITEM AS TOTAL_INSPECCION,
					@VP_POSICION_INSPECCION	AS POSICION_INSPECCION
					-- =============================	
			FROM	INSPECCION_MATERIAL (NOLOCK)
					-- =============================
					INNER JOIN ESTATUS_INSPECCION_MATERIAL (NOLOCK) ON INSPECCION_MATERIAL.K_ESTATUS_INSPECCION_MATERIAL = ESTATUS_INSPECCION_MATERIAL.K_ESTATUS_INSPECCION_MATERIAL
					INNER JOIN TIPO_INSPECCION_MATERIAL (NOLOCK) ON INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL = TIPO_INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL
					INNER JOIN INSPECCION_OPCION (NOLOCK) ON INSPECCION_MATERIAL.K_INSPECCION_MATERIAL = INSPECCION_OPCION.K_INSPECCION_MATERIAL
					INNER JOIN BD_GENERAL.dbo.USUARIO_PEARL (NOLOCK) ON INSPECCION_MATERIAL.K_USUARIO_CAMBIO = BD_GENERAL.dbo.USUARIO_PEARL.K_USUARIO_PEARL
					-- =============================
					LEFT  JOIN INSPECCION_LOTE_PIEL (NOLOCK) ON INSPECCION_LOTE_PIEL.K_INSPECCION_MATERIAL = INSPECCION_MATERIAL.K_INSPECCION_MATERIAL
							AND INSPECCION_LOTE_PIEL.K_ITEM = INSPECCION_MATERIAL.K_ITEM
							AND	INSPECCION_LOTE_PIEL.K_IMPORTACION_LOTE_PIEL = @PP_K_LOTE_IMPORTACION
							AND INSPECCION_LOTE_PIEL.LOTE = @PP_LOTE
					-- =============================
			WHERE	INSPECCION_MATERIAL.K_ITEM = @PP_K_ITEM
			AND		INSPECCION_MATERIAL.K_INSPECCION_MATERIAL = @PP_K_INSPECCION_MATERIAL 
			-- =============================
			ORDER BY INSPECCION_MATERIAL.K_INSPECCION_MATERIAL DESC
		END
	-- ////////////////////////////////////////////////
	-- ////////////////////////////////////////////////
GO



