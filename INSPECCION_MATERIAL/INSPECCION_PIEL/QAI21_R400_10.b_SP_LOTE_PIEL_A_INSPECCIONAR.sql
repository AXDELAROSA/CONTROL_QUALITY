	@PP_K_SISTEMA_EXE				INT,
	@PP_K_USUARIO_ACCION			INT,
	-- ===========================
	@PP_K_LOTE_IMPORTACION			INT,
	@PP_K_ITEM						INT,
	@PP_LOTE						INT
	
AS

	-- ///////////////////////////////////////////
	SELECT	
			[INSPECCION_LOTE_PIEL].*,
			D_USUARIO_PEARL AS D_USUARIO_CAMBIO,
			INSPECCION_MATERIAL.*,
			INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL,
			LTRIM(RTRIM([DESCRIPTION])) AS COLOR,
			IncInsp_sql.Lot_size	AS CANTIDAD_LOTE
	-- =============================	
	FROM	[INSPECCION_LOTE_PIEL] (NOLOCK)
	INNER JOIN IncInsp_sql (NOLOCK) ON ID = K_IMPORTACION_LOTE_PIEL
	INNER JOIN INSPECCION_MATERIAL (NOLOCK) ON [INSPECCION_LOTE_PIEL].K_INSPECCION_MATERIAL = INSPECCION_MATERIAL.K_INSPECCION_MATERIAL
			AND [INSPECCION_LOTE_PIEL].K_ITEM = INSPECCION_MATERIAL.K_ITEM
	INNER JOIN	TIPO_INSPECCION_MATERIAL (NOLOCK) ON INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL = TIPO_INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL
	INNER JOIN BD_GENERAL.dbo.USUARIO_PEARL (NOLOCK) ON [INSPECCION_LOTE_PIEL].K_USUARIO_CAMBIO = BD_GENERAL.dbo.USUARIO_PEARL.K_USUARIO_PEARL
	-- =============================
	WHERE	[K_IMPORTACION_LOTE_PIEL] = @PP_K_LOTE_IMPORTACION
	AND		[INSPECCION_LOTE_PIEL].K_ITEM = @PP_K_ITEM
	AND		LOTE = @PP_LOTE

	-- ////////////////////////////////////////////////
	-- ////////////////////////////////////////////////
GO




