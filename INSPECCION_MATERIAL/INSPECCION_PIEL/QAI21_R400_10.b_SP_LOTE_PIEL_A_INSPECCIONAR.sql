	DECLARE @VP_N_PIEL_INSPECCIONADA INT = 0
	SELECT	@VP_N_PIEL_INSPECCIONADA = COUNT(DISTINCT(PIEL)) 
	FROM	INSPECCION_LOTE_PIEL_GROSS_SUAVIDAD (NOLOCK)
	INNER	JOIN INSPECCION_MATERIAL (NOLOCK) ON INSPECCION_MATERIAL.K_INSPECCION_MATERIAL = INSPECCION_LOTE_PIEL_GROSS_SUAVIDAD.K_INSPECCION_MATERIAL
	WHERE	[K_IMPORTACION_LOTE_PIEL]	= @PP_K_LOTE_IMPORTACION
	AND		INSPECCION_LOTE_PIEL_GROSS_SUAVIDAD.[K_ITEM] = @PP_K_ITEM						
	AND		[LOTE] = @PP_LOTE							
	AND		[K_TIPO_INSPECCION_MATERIAL] = @PP_K_TIPO_INSPECCION_MATERIAL

	IF @VP_N_PIEL_INSPECCIONADA IS NULL
		SET @VP_N_PIEL_INSPECCIONADA = 0

	IF @VP_CANTIDAD_MUESTRA <> @VP_N_PIEL_INSPECCIONADA
		BEGIN
			DECLARE @VP_K_INSPECCION INT = 0
			SELECT @VP_K_INSPECCION = K_INSPECCION_MATERIAL
			FROM INSPECCION_MATERIAL (NOLOCK)
			INNER	JOIN TIPO_INSPECCION_MATERIAL (NOLOCK) ON INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL = TIPO_INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL
			WHERE K_ITEM = @PP_K_ITEM AND K_ESTATUS_INSPECCION_MATERIAL = 1 
			AND INSPECCION_MATERIAL.K_TIPO_INSPECCION_MATERIAL = @PP_K_TIPO_INSPECCION_MATERIAL

			SET @VP_MENSAJE = @VP_K_INSPECCION
		END

	--	////////////////////////////////////////////////
	SELECT	@VP_MENSAJE AS MENSAJE
			

	-- ////////////////////////////////////////////////
	-- ////////////////////////////////////////////////
GO



