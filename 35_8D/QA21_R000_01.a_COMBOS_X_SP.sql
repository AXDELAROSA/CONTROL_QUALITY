/*
	EXEC	[dbo].[PG_CB_8D_ROL] 0,0,	 0
*/
CREATE PROCEDURE [dbo].[PG_CB_8D_ROL]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO				INT,
	--============================
	@PP_TODOS					INT
AS

	DECLARE @VP_TA_CATALOGO	AS TABLE
				(	TA_K_CATALOGO		INT,
					TA_D_CATALOGO		VARCHAR(50))

	INSERT INTO @VP_TA_CATALOGO 
	SELECT	1, 'CHAMPION'

	INSERT INTO @VP_TA_CATALOGO 
	SELECT	2, 'TEAM LEADER' 

	INSERT INTO @VP_TA_CATALOGO 
	SELECT	2, 'TEAM MEMBERS' 


	-- ///////////////////////////////////////////////////
	SELECT	TA_K_CATALOGO	AS K_COMBOBOX,
				TA_D_CATALOGO	AS D_COMBOBOX 
		FROM	@VP_TA_CATALOGO
		ORDER BY  TA_K_CATALOGO 

	-- ==========================================
		
	-- ////////////////////////////////////////////////////
GO


