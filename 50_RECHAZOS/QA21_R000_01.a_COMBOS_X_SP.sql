IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[PG_CB_PERFORACION_MODELO]') AND type in (N'P', N'PC'))
	DROP PROCEDURE [dbo].[PG_CB_PERFORACION_MODELO]
GO

/*
	EXEC	[dbo].[PG_CB_PERFORACION_MODELO] 0,0,	 0
*/
CREATE PROCEDURE [dbo].[PG_CB_PERFORACION_MODELO]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO				INT,
	--============================
	@PP_TODOS					INT
AS

	DECLARE @VP_TA_CATALOGO	AS TABLE
				(	TA_K_CATALOGO		VARCHAR(20),
					TA_D_CATALOGO		VARCHAR(50))
	
	INSERT INTO @VP_TA_CATALOGO
	 SELECT LTRIM(RTRIM(PROD_CAT)),
			CONCAT(LTRIM(RTRIM(PROD_CAT)), ' // ', LTRIM(RTRIM(PROD_CAT_DESC)))
	 FROM IMCATFIL_SQL 
	 WHERE  L_BORRADO = 0

	 INSERT INTO @VP_TA_CATALOGO
	 SELECT '( TODOS )',
			'( TODOS )'


	-- ///////////////////////////////////////////////////
	SELECT	TA_K_CATALOGO	AS K_COMBOBOX,
				TA_D_CATALOGO	AS D_COMBOBOX 
		FROM	@VP_TA_CATALOGO
		ORDER BY  TA_K_CATALOGO 

	-- ==========================================
		
	-- ////////////////////////////////////////////////////
GO


